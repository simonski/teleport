"""Real-browser checks for view-aware creation and ticket keyboard ownership."""
import json

def verify_todo_menu(browser, project_id, ticket):
    browser("eval", "document.querySelector('#cookie-notice [data-storage=reject]')?.click()")
    browser("wait", "#project + .choice-button")
    browser("select", "#project", str(project_id))
    browser("wait", "--fn", "document.querySelector('#account-project-settings')?.textContent==='Project'")
    browser("click", "#account")
    browser("eval", "if(document.querySelector('#account-project-settings')?.textContent!=='Project')throw new Error('Profile project action has the wrong label')")
    browser("click", "#account-project-settings")
    browser("wait", "--fn", "document.querySelector('#editor h2')?.textContent==='Project · Smoke flight'")
    browser("press", "Escape")
    browser("click", '#nav-views [data-view="Todos"]')
    card = f'.ticket-open[data-ticket="{ticket["id"]}"]'
    browser("wait", card)
    def menu():
        browser("eval", f'document.querySelector({json.dumps(card)}).focus()')
        browser("press", "Shift+F10")
        browser("wait", '[data-ticket-menu="open"]')
    def lane(role):
        browser("wait", "--fn", f'document.querySelector({json.dumps(card)})?.closest(".lane")?.querySelector("h2")?.textContent==={json.dumps(role)}')
    lane('Doing')
    menu()
    browser("eval", "if(!['ahead','behind','status','priority','open','delete'].every(id=>document.querySelector('[data-ticket-menu='+id+']')))throw new Error('Missing Todos menu item')")
    browser("click", '[data-ticket-menu="behind"]')
    lane('Todo')
    menu()
    browser("click", '[data-ticket-menu="ahead"]')
    lane('Doing')
    menu()
    browser("click", '[data-ticket-menu="priority"]')
    browser("click", '[data-ticket-priority="high"]')
    browser("wait", "--fn", f'tickets.some(t=>t.id==={ticket["id"]}&&t.priority==="high")')
    menu()
    browser("click", '[data-ticket-menu="status"]')
    browser("find", "role", "menuitem", "click", "--name", "Done", "--exact")
    browser("wait", '#agreement')
    browser("press", "Escape")
    lane('Doing')
    menu()
    browser("click", '[data-ticket-menu="delete"]')
    browser("wait", "--fn", "document.querySelector('#editor h2')?.textContent==='Delete ticket'")
    browser("click", '#editor button[type="submit"]')
    browser("wait", "--fn", f'!document.querySelector({json.dumps(card)})')

def verify_shortcut_project(browser, tk, project_id):
    browser("eval", "document.querySelector('#cookie-notice [data-storage=reject]')?.click()")
    browser("wait", "#project + .choice-button")
    browser("select", "#project", str(project_id))
    browser("eval", "document.activeElement?.blur()")
    browser("press", "n")
    browser("wait", '#editor [name="title"]')
    browser("eval", "if(document.querySelector('#editor [name=projectId]')||!document.querySelector('#editor').textContent.includes('Smoke flight'))throw new Error('Selected project was not used directly')")
    browser("fill", '#editor [name="title"]', "Shortcut project proof")
    browser("click", '#editor button[type="submit"]')
    browser("wait", "--fn", "!document.querySelector('tk-dialog[open]')")
    browser("wait", "--fn", "document.querySelector('#notice')?.textContent==='Ticket created'")
    items = json.loads(tk("listTickets", "--data", json.dumps({"projectId": project_id})))['items']
    assert any(item['title'] == 'Shortcut project proof' and item['projectId'] == project_id for item in items)
    browser("select", "#project", "0")
    browser("eval", "document.activeElement?.blur()")
    browser("press", "n")
    browser("wait", '#editor [name="projectId"]')
    browser("eval", "if(!document.querySelector('#editor [name=projectId]').required||document.querySelector('#editor [name=projectId]').value!=='')throw new Error('All projects did not require a project choice')")
    browser("press", "Escape")
    browser("select", "#project", str(project_id))
    browser("eval", "document.activeElement?.blur();window.ticketProofRole=roleAllowsWrite;roleAllowsWrite=()=>false")
    browser("press", "n")
    browser("eval", "roleAllowsWrite=window.ticketProofRole;if(document.querySelector('tk-dialog[open]')||!document.querySelector('#notice').textContent.includes('does not permit'))throw new Error('Read-only project did not refuse creation')")


def verify_ticket_keyboard(browser, tk, project_id):
    def call(operation, data):
        return json.loads(tk(operation, "--data", json.dumps(data)))

    def focused(ticket):
        browser("eval", f"if(document.activeElement?.dataset.ticket!=={json.dumps(str(ticket['id']))})throw new Error('Wrong ticket focus '+JSON.stringify({{actual:document.activeElement?.dataset.ticket,expected:{ticket['id']},foreground:!!foregroundOpen(),lanes:[...document.querySelectorAll('.board .lane')].map(lane=>[...lane.querySelectorAll('.ticket-open')].map(node=>node.dataset.ticket))}}))")

    before = call("listTickets", {"projectId": project_id})["items"]
    for view, kind, intent in [("Goals", "goal", "agent"), ("Epics", "epic", "agent"), ("Todos", "task", "human")]:
        browser("click", f'#nav-views [data-view="{"Backlog" if view in ("Goals","Epics") else view}"]')
        if view in ("Goals","Epics"):
            browser("select", "#backlog-kind", kind)
        for trigger in ["button", "key"]:
            if trigger == "button":
                browser("eval", "document.activeElement?.blur()"); browser("press", "n")
            else:
                browser("press", "n")
            browser("wait", '#editor [name="title"]')
            browser("eval", f"if(document.querySelector('[name=kind]').value!=={json.dumps(kind)}||document.querySelector('[name=intent]').value!=={json.dumps(intent)}||document.activeElement!==document.querySelector('[name=title]'))throw new Error('Wrong creation context or focus')")
            browser("press", "n")
            browser("eval", "if(document.querySelector('[name=title]').value!=='n')throw new Error('Shortcut stole editor text input')")
            browser("press", "Escape")
    assert call("listTickets", {"projectId": project_id})["items"] == before

    created = [call("createTicket", {"projectId": project_id, "title": title, "agent": False, "requestId": "keyboard-" + str(index)}) for index, title in enumerate(["Keyboard first", "Keyboard second", "Keyboard next lane"])]
    created[2] = call("transitionTicket", {"id": created[2]["id"], "expectedVersion": created[2]["version"], "target": "Doing"})
    browser("click", '#nav-views [data-view="Board"]')
    browser("select", "#lens", "human")
    browser("eval", "document.activeElement?.blur()"); browser("press", "n")
    browser("eval", "if(document.querySelector('[name=kind]').value!=='task'||document.querySelector('[name=intent]').value!=='human')throw new Error('Board lens ignored')")
    browser("press", "Escape")
    browser("wait", f'.ticket-open[data-ticket="{created[0]["id"]}"]')
    browser("wait", "--fn", json.dumps([str(ticket["id"]) for ticket in created]) + ".every(id=>document.querySelector('.ticket-open[data-ticket=\"'+id+'\"]'))")
    browser("wait", "--fn", "document.querySelector('.ticket-open[data-ticket=\"" + str(created[2]["id"]) + "\"]')?.closest('.lane')?.querySelector('h2')?.textContent==='Doing'")
    browser("eval", f'document.querySelector(\'.ticket-open[data-ticket="{created[0]["id"]}"]\').focus()')
    browser("press", "ArrowDown"); focused(created[1])
    browser("press", "ArrowDown"); focused(created[1])
    browser("press", "ArrowRight"); focused(created[2])
    browser("press", "ArrowLeft"); focused(created[1])
    browser("press", "ArrowUp"); focused(created[0])
    changed = call("updateTicket", {"id": created[0]["id"], "expectedVersion": created[0]["version"], "priority": "high"})
    created[0] = changed
    browser("wait", "--fn", f'tickets.some(t=>t.id==={changed["id"]}&&t.version==={changed["version"]})')
    focused(created[0])
    browser("screenshot", "/tmp/teleport-board-keyboard.png")
    browser("press", "Shift+F10")
    browser("wait", '[data-ticket-menu="open"]')
    browser("eval", "if(document.querySelector('[data-ticket-menu=teleport],[data-ticket-menu=questions]'))throw new Error('Menu offered an unavailable session or question')")
    browser("press", "End"); browser("press", "Home")
    browser("screenshot", "/tmp/teleport-ticket-menu.png")
    browser("press", "Escape"); focused(created[0])
    point = json.loads(browser("eval", f'(()=>{{const r=document.querySelector(\'.ticket-open[data-ticket="{created[0]["id"]}"]\').getBoundingClientRect();return {{x:r.x+r.width/2,y:r.y+r.height/2}};}})()'))
    browser("mouse", "move", str(round(point["x"])), str(round(point["y"])))
    browser("mouse", "down", "right"); browser("mouse", "up", "right")
    browser("wait", '[data-ticket-menu="open"]')
    browser("mouse", "move", "3", "130"); browser("mouse", "down", "left"); browser("mouse", "up", "left")
    browser("wait", "--fn", "!ticketMenuBusy()")
    browser("eval", f'document.querySelector(\'.ticket-open[data-ticket="{created[0]["id"]}"]\').focus()')
    browser("press", "e")
    browser("wait", '#editor [name="title"]')
    browser("eval", "if(document.querySelector('#editor [name=title]').value!=='Keyboard first')throw new Error('E opened a different record')")
    browser("press", "Escape"); focused(created[0])
    browser("click", '#nav-views [data-view="Graph"]')
    source = f'#graph-list [data-node="ticket:{created[0]["id"]}"]'
    browser("wait", source)
    browser("click", source)
    browser("press", "Shift+F10")
    browser("wait", '[data-ticket-menu="open"]')
    browser("press", "Enter")
    browser("wait", '#editor [name="title"]')
    browser("eval", "if(document.querySelector('#editor [name=title]').value!=='Keyboard first')throw new Error('Graph menu opened a different record')")
    browser("press", "Escape")
    browser("wait", '#graph-stage canvas')
    browser("eval", "document.querySelector('#graph-stage canvas').focus()")
    browser("press", "Shift+F10")
    browser("wait", '[data-ticket-menu="open"]')
    browser("press", "Escape")
    browser("eval", "if(document.activeElement!==document.querySelector('#graph-stage canvas')||Object.keys(graphPending).length)throw new Error('Graph menu lost focus or changed arrangement')")
    browser("click", '#nav-views [data-view="Todos"]')
    browser("set", "viewport", "390", "844")
    browser("eval", f'document.querySelector(\'.ticket-open[data-ticket="{created[0]["id"]}"]\').focus()')
    browser("press", "Shift+F10")
    browser("wait", '[data-ticket-menu="open"]')
    browser("eval", "{const r=document.querySelector('.ticket-context-menu').getBoundingClientRect();if(r.left<0||r.right>innerWidth||r.top<0||r.bottom>innerHeight)throw new Error('Ticket menu is outside the viewport');}")
    browser("screenshot", "/tmp/teleport-ticket-menu-mobile.png")
    browser("press", "Escape");focused(created[0])
    browser("set", "viewport", "1280", "800")
    for ticket in created:
        assert call("getTicket", {"id": ticket["id"]})["version"] == ticket["version"], "Keyboard navigation mutated work"
        call("setTicketVisibility", {"id": ticket["id"], "expectedVersion": ticket["version"], "archived": True})
    browser("click", '#nav-views [data-view="Board"]')
    browser("select", "#lens", "agent")
    browser("click", '#nav-views [data-view="Home"]')
    print("PASS: view-aware New/N, editor input ownership, Board arrows/E, real pointer/keyboard ticket menus, Graph list/canvas menus and focus without ticket-state or arrangement mutation")
