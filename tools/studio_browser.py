"""Real-browser acceptance for the reference-inspired maps, focus and appearance."""
import json


def verify_studio(browser,tk,project,ticket,stage=lambda name:None):
    stage("studio-appearance")
    def call(operation,data):
        return json.loads(tk(operation,"--data",json.dumps(data)))
    browser("set","viewport","1600","1000")
    goal=call("createTicket",{"projectId":project["id"],"kind":"goal","title":"A calmer boarding experience","agent":False,"requestId":"studio-goal"})
    epic=call("createTicket",{"projectId":project["id"],"kind":"epic","parentId":goal["id"],"title":"Build the boarding workflow","agent":False,"requestId":"studio-epic"})
    tasks=[]
    for index,title in enumerate(("Connect the workspace","Build the task interface","Run acceptance checks","Review and ship")):
        task=call("createTicket",{"projectId":project["id"],"parentId":epic["id"],"title":title,"agent":False,"requestId":"studio-task-"+str(index)})
        if index<2:
            task=call("transitionTicket",{"id":task["id"],"expectedVersion":task["version"],"target":"Doing"})
        tasks.append(task)
    browser("find","role","button","click","--name","Settings","--exact")
    browser("select","#appearance-style","studio")
    browser("select","#navigation-position","left")
    browser("wait","--fn","!preferenceSaving&&!Object.keys(preferenceDraft).length")
    browser("press","Escape")
    browser("find","role","button","click","--name","Graph","--exact")
    stage("studio-graph")
    browser("click","#graph-2d")
    browser("wait","--fn","graphRuntime?.scene.snapshot().projection==='2d'&&graphRuntime.scene.snapshot().flowingEdges>0")
    selector='[data-graph-node="ticket:'+str(epic["id"])+'"]'
    browser("hover",selector)
    browser("wait","--fn","document.querySelectorAll('.graph2d-muted').length>0")
    browser("eval","if(new Set([...document.querySelectorAll('.graph2d-icon path')].map(path=>path.getAttribute('d'))).size<4)throw new Error('Entity icons are not distinct')")
    browser("screenshot","/tmp/teleport-graph-2d-studio-left.png")
    snapshot=json.loads(browser("eval","graphRuntime.scene.snapshot()"))
    browser("wait","--fn","graphRuntime.scene.snapshot().phase>"+str(snapshot["phase"]+.005))
    corner=json.loads(browser("eval","(()=>{const r=document.querySelector('#graph-stage').getBoundingClientRect();return {x:r.x+6,y:r.y+6}})()"))
    browser("mouse","move",str(corner["x"]),str(corner["y"]))
    browser("wait","--fn","!document.querySelector('.graph2d-muted')")
    browser("click",selector)
    before=json.loads(browser("eval","graphData.nodes.find(node=>node.id==='ticket:"+str(epic["id"])+"').position"))
    browser("press","Alt+ArrowDown")
    browser("wait","--fn","Object.keys(graphPending).length===1")
    browser("click","#graph-save")
    browser("wait","--fn","!Object.keys(graphPending).length")
    saved=call("getGraph",{"projectId":project["id"],"projection":"2d"})
    assert saved["layout"]["positions"]["ticket:"+str(epic["id"])]["y"]==before["y"]-10
    assert call("getGraph",{"projectId":project["id"]})["layout"]["version"]==0
    assert call("getTicket",{"id":epic["id"]})["version"]==epic["version"]
    browser("set","media","light","reduced-motion")
    browser("wait","--fn","!graphRuntime.scene.snapshot().animationRunning")
    browser("set","media","light")
    browser("find","role","button","click","--name","Settings","--exact")
    browser("select","#navigation-position","top")
    browser("wait","--fn","!preferenceSaving&&!Object.keys(preferenceDraft).length")
    browser("press","Escape")
    browser("screenshot","/tmp/teleport-graph-2d-studio-top.png")
    browser("select","#project","manage-projects")
    stage("studio-table")
    browser("click",'[data-project-presentation="list"]')
    browser("wait",".project-table")
    browser("screenshot","/tmp/teleport-studio-project-table.png")
    browser("press","Escape")
    browser("find","role","button","click","--name","Workflows","--exact")
    stage("studio-workflow-map")
    browser("wait","#workflow-view-map")
    browser("click","#workflow-view-map")
    browser("wait","#workflow-map-stage canvas")
    browser("wait","--fn","!!workflowMapRuntime")
    original=json.loads(browser("eval","JSON.stringify(flow)"))
    browser("click","#workflow-map-trace")
    browser("wait","--fn","workflowMapRuntime?.scene.snapshot().flowingEdges>0")
    browser("eval","window.scrollTo({top:0,behavior:'instant'})")
    browser("screenshot","/tmp/teleport-studio-workflow-map.png")
    browser("click","#workflow-view-editor")
    assert json.loads(browser("eval","JSON.stringify(flow)"))==original
    browser("wait","#phase-rows")
    browser("click","#flow-copy")
    stage("studio-workflow-draft")
    browser("wait",'#editor [name="title"]')
    browser("fill",'#editor [name="title"]',"Boarding workflow")
    browser("click",'#editor button[type="submit"]')
    browser("wait","--fn","!!flow&&!flow.published&&!workflowLoading&&!document.querySelector('tk-dialog[open]')")
    definition=json.loads(browser("eval","({phases:flow.phases,rules:flow.rules,key:flowKey(flow)})"))
    browser("click","#workflow-view-map")
    browser("wait","--fn","!!workflowMapRuntime")
    phase=definition["phases"][0]["id"]
    browser("click",'[data-graph-node='+json.dumps(phase)+']')
    browser("press","Alt+ArrowRight")
    browser("wait","--fn","flowDirty")
    browser("click","#flow-save")
    browser("wait","--fn","!flowDirty&&!workflowMutation&&!!workflowMapRuntime")
    persisted=call("getWorkflow",{"workflowKey":definition["key"]})
    assert persisted["phases"]==definition["phases"] and persisted["rules"]==definition["rules"] and phase in persisted["layout"]
    browser("eval","window.scrollTo({top:0,behavior:'instant'})")
    browser("screenshot","/tmp/teleport-studio-workflow-map-draft.png")
    browser("find","role","button","click","--name","Settings","--exact")
    stage("studio-dark-mobile")
    browser("select","#appearance-mode","dark")
    browser("wait","--fn","!preferenceSaving&&!Object.keys(preferenceDraft).length")
    browser("press","Escape")
    browser("click","#workflow-view-map")
    browser("wait","#workflow-map-stage canvas")
    browser("screenshot","/tmp/teleport-studio-workflow-map-dark.png")
    browser("set","viewport","390","844")
    browser("eval","if(document.documentElement.scrollWidth>innerWidth)throw new Error('Studio overflows mobile')")
    browser("screenshot","/tmp/teleport-studio-mobile.png")
    print("PASS: Three.js 2D cards/curves/icons, moving flow, hover restoration, independent layout save, reduced motion, Studio top/left/table/dark/mobile and workflow Map without definition mutation")
